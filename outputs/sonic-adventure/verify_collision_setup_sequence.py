"""Real world/debug initialization then the existing collision entry on the same RAM."""
import hashlib,itertools,json,struct
from pathlib import Path
import collision_setup_fixtures as fixture
P=fixture.P


def main():
    ram=fixture.v.seed_ram();records=[];checks=0
    def require(ok,label):
        nonlocal checks
        assert ok,label;checks+=1
    for bank,variant in itertools.product((0,4),(0,2)):
        m,s,f,cfg=fixture.prepare(ram,dict(entry=fixture.WORLD_INIT,mode=bank,variant_input=variant))
        query=0x8cc00000
        for i,value in enumerate((1,.5,.25,.5,0,0,0)):
            fixture.put(m,query+4*i,int.from_bytes(struct.pack('<f',value),'little'))
        before_query=bytes(m[query&0xffffff:(query&0xffffff)+0x1c])
        for entry,args in ((fixture.WORLD_INIT,()),(fixture.DEBUG_INIT,()),(0x8c029b00,(query,0x12345678))):
            cfg['entry']=entry;s.pc=entry;s.pr=0x8cfed000
            for j,arg in enumerate(args):s.r[4+j]=arg
            initial_sp=s.r[15]
            result,path,m,s,f=fixture.fast.compare(m,s,f,cfg)
            require(result['status']==0 and result['full_state_match'] and result['ordered_boundaries_match'],'original/native sequence stage')
            require(s.pc==s.pr==0x8cfed000 and s.r[15]==initial_sp,'stage return/stack')
            require(fixture.get(m,0x8c02d548)==0 and fixture.get(m,0x8c73e400)==0,'actual initialized empty world and zero contacts')
            if entry!=fixture.WORLD_INIT:require(fixture.get(m,0x8c752bdc,1)==255,'debug flag generated by real initializer')
            if entry==0x8c029b00:
                require(s.r[0]==0,'empty initialized world returns no collision')
                require(bytes(m[query&0xffffff:(query&0xffffff)+0x1c])==before_query,'authored query inputs preserved')
            records.append(dict(mode=bank,variant_input=variant,entry=hex(entry),status=0,original_rows=len(path),
                                result=s.r[0],boundaries=result['boundaries'],world_head=0,contact_count=0,
                                debug_flag=fixture.get(m,0x8c752bdc,1),full_state_match=True,ordered_boundaries_match=True))
            print('SETUP SEQUENCE',len(records),hex(entry),'PASS',flush=True)
    files=[Path(__file__),P/'collision_setup_fixtures.py',P/'collision_setup_reference.py',
      P/'write_watch_collision_setup.py',fixture.v.MP,P/'analysis/collision_setup_connection.json',fixture.v.effects.DLL]
    report=dict(original_native_comparisons=len(records),independent_checks=checks,cases=records,
      dll_sha256=hashlib.sha256(fixture.v.effects.DLL.read_bytes()).hexdigest(),
      supplied_game_callee_outputs=0,supplied_execution_frames=0,new_original_routine_credit=0,
      sha256={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in files},
      scope='Four same-RAM original/native worldinit->debuginit->029b00 empty-world sequences, both FP banks '
      'and two authored initial variant flags. Host starts each ordinary call with arguments and return address; '
      'no execution checkpoint or callee result installed. World head/counter/debug flags are generated by actual '
      'initialization. This is not complete cold startup, world population, movement, renderer initialization or gameplay.')
    (P/'analysis/collision_setup_sequence_verification.json').write_text(json.dumps(report,indent=2)+'\n')
    print('SETUP SEQUENCE PASS',len(records),checks,flush=True)


if __name__=='__main__':main()

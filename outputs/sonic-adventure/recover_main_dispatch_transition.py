"""Generate static C for the retail main-dispatch transition helper.

The executable uses original-PC labels, not runtime opcode decoding. Ordinary
integer translations reuse the established helper translator without executing
its file-writing entry point. FPU widths and branches are handled explicitly.
"""
import ast
import csv
import hashlib
import json
import re
import struct
from pathlib import Path

P = Path(__file__).resolve().parent
ROOT = P.parents[1]
START, END = 0x8C0AFF1A, 0x8C0B07E4
NAME = 'sa_main_dispatch_transition_8c0aff1a'
LISTING = P / 'analysis/main-dispatch-helpers/8c0aff1a_instructions.tsv'
TRANSLATOR = P / 'ghidra/translate_tikal_helper.py'
BINARY = ROOT / 'work/sonic-adventure/extracted/1ST_READ.BIN'
binary = BINARY.read_bytes()
assert hashlib.sha256(binary).hexdigest() == '45bc5d3c25dcfe2cc2c5701311d46783f33e4daa44a951cd9896724d66f0367a'
rows = {}
for row in csv.DictReader(LISTING.open(), delimiter='\t'):
    address = int(row['address'], 16)
    raw = bytes.fromhex(row['bytes'])
    assert len(raw) == int(row['length']) == 2 and START <= address < END
    assert binary[address - 0x8C010000:address - 0x8C010000 + 2] == raw
    assert address not in rows
    rows[address] = int.from_bytes(raw, 'little'), row['instruction'].lstrip('_')


def sx(value, bits):
    return value - (1 << bits) if value & (1 << (bits - 1)) else value


targets = [0x8C0AFFBC + struct.unpack_from('<h', binary, 0x8C0AFFC0 - 0x8C010000 + 2*i)[0]
           for i in range(50)]
# Independent raw-opcode reachability, with calls returning after their delay
# slots and the signed-offset switch decoded above. It excludes literal pools.
seen, pending, calls, branch_edges = set(), [START], [], []
while pending:
    a = pending.pop()
    if a in seen:
        continue
    assert a in rows, f'missing reachable instruction {a:08x}'
    seen.add(a)
    w = rows[a][0]
    if w == 0x000B or w >> 12 in (0xA, 0xB) or w & 0xF0FF == 0x400B or w == 0x0023:
        assert a+2 in rows
        seen.add(a+2)
        if w == 0x000B:
            continue
        if w == 0x0023:
            assert a == 0x8C0AFFB8
            pending.extend(targets)
            branch_edges.extend((a,t) for t in sorted(set(targets)))
        elif w >> 12 == 0xA:
            target = a+4+2*sx(w & 0xFFF,12)
            pending.append(target)
            branch_edges.append((a,target))
        else:
            calls.append(a)
            pending.append(a+4)
    elif w >> 8 in (0x89,0x8B,0x8D,0x8F):
        target = a+4+2*sx(w & 255,8)
        fallthrough = a+4 if w >> 8 in (0x8D,0x8F) else a+2
        if fallthrough == a+4:
            assert a+2 in rows
            seen.add(a+2)
        pending.extend((target,fallthrough))
        branch_edges.extend(((a,target),(a,fallthrough)))
    else:
        pending.append(a+2)
assert seen == set(rows), (len(seen),len(rows),set(rows)-seen)
assert len(rows)==957 and len(calls)==34 and len(set(targets))==45

module = ast.parse(TRANSLATOR.read_text())
simple_node = next(node for node in module.body if isinstance(node, ast.FunctionDef) and node.name=='simple')
namespace = {'re':re,'rows':rows}
exec(compile(ast.Module(body=[simple_node],type_ignores=[]),str(TRANSLATOR),'exec'),namespace)
integer_simple = namespace['simple']


def simple(a):
    w, text = rows[a]
    n, m = w>>8 & 15, w>>4 & 15
    if text.startswith('fmov'):
        form=w & 15
        if form==6:
            return f'fload(m,f,{n}u,r[0]+r[{m}]);'
        if form in (8,9):
            return f'fload(m,f,{n}u,r[{m}]);'+(f'r[{m}]+=fwidth(f);' if form==9 else '')
        if form in (7,10,11):
            address=f'r[0]+r[{n}]' if form==7 else f'r[{n}]'
            return (f'r[{n}]-=fwidth(f);' if form==11 else '')+f'fstore(m,f,{m}u,{address});'
        raise ValueError((hex(a),text))
    if w & 0xF0FF==0xF08D:
        return f'f->bank[(f->fpscr>>21)&1u][{n}]=0u;'
    if w & 0xF00F in (0xF000,0xF001):
        return (f'{{uint32_t *fr=f->bank[(f->fpscr>>21)&1u];'
                f'status=sa_sh4_add_sub(&fr[{n}],&fr[{m}],&f->fpscr,&fr[{n}],{w&1});'
                'if(status)return status;}')
    if w & 0xF00F==0xF005:
        return (f'status=sa_sh4_compare_bits(f->bank[(f->fpscr>>21)&1u][{n}],'
                f'f->bank[(f->fpscr>>21)&1u][{m}],&f->fpscr,sr,1);if(status)return status;')
    assert not text.startswith('f'), (hex(a),text)
    return integer_simple(a)


header = '''/* Generated by recover_main_dispatch_transition.py from retail bytes.
 * Main dispatcher transition helper; inferred descriptive name, not a symbol.
 * Static C control flow; RAM is a caller-supplied 16 MiB Dreamcast image.
 * Host return 0 = completed; retail result is R0. -1 = unsupported FPSCR.PR,
 * -2 = missing callback or unexpected switch destination. Callback errors
 * propagate with partial machine state. Exceptions and MMIO are not modeled.
 * All 34 external call sites remain explicit services, not recovered callees.
 */
#include "fpu_cleanup_transfer.h"
#include "sh4_add_sub.h"
#include "sh4_compare_bits.h"
typedef int (*sa_transition_service)(void *,uint32_t,uint8_t *,
    struct sa_fpu_banks *,uint32_t *,uint32_t *,uint32_t *);
static uint32_t rd(uint8_t *m,uint32_t a,unsigned n){
 uint32_t v=0;for(unsigned i=0;i<n;i++)v|=(uint32_t)m[(a&0xffffffu)+i]<<(i*8);return v;
}
static uint32_t sx(uint8_t *m,uint32_t a,unsigned n){
 uint32_t v=rd(m,a,n);return n==1?(uint32_t)(int32_t)(int8_t)v:(uint32_t)(int32_t)(int16_t)v;
}
static void wr(uint8_t *m,uint32_t a,uint32_t v,unsigned n){
 for(unsigned i=0;i<n;i++)m[(a&0xffffffu)+i]=(uint8_t)(v>>(i*8));
}
static uint32_t fwidth(const struct sa_fpu_banks *f){return f->fpscr&0x100000u?8u:4u;}
static void fload(uint8_t *m,struct sa_fpu_banks *f,unsigned reg,uint32_t a){
 unsigned bank=(f->fpscr>>21)&1u;
 if(f->fpscr&0x100000u){bank^=reg&1u;reg&=~1u;
  f->bank[bank][reg]=rd(m,a,4);f->bank[bank][reg+1]=rd(m,a+4u,4);
 }else f->bank[bank][reg]=rd(m,a,4);
}
static void fstore(uint8_t *m,struct sa_fpu_banks *f,unsigned reg,uint32_t a){
 unsigned bank=(f->fpscr>>21)&1u;
 if(f->fpscr&0x100000u){bank^=reg&1u;reg&=~1u;
  wr(m,a,f->bank[bank][reg],4);wr(m,a+4u,f->bank[bank][reg+1],4);
 }else wr(m,a,f->bank[bank][reg],4);
}
SA_STAGE_EXPORT int sa_main_dispatch_transition_8c0aff1a(
 uint8_t *m,struct sa_fpu_banks *f,uint32_t *sr,uint32_t *r,uint32_t *pr,
 uint32_t *fpul,uint32_t *macl,void *ctx,sa_transition_service call){
 (void)fpul;(void)macl;
 if(f->fpscr&0x80000u)return -1;
 if(!call)return -2;
 int status,take;uint32_t target;
 goto L8c0aff1a;
'''
out, delay_slots = [], set()
for a,(w,text) in sorted(rows.items()):
    if a in delay_slots:
        continue
    terminal=False
    if w >> 8 in (0x89,0x8B,0x8D,0x8F):
        dest=a+4+2*sx(w&255,8)
        condition='(*sr&1u)' if w>>8 in (0x89,0x8D) else '!(*sr&1u)'
        if w>>8 in (0x8D,0x8F):
            code=f'take={condition};'+simple(a+2)+f'if(take)goto L{dest:x};goto L{a+4:x};'
            delay_slots.add(a+2)
        else:
            code=f'if({condition})goto L{dest:x};goto L{a+2:x};'
        terminal=True
    elif w>>12==0xA:
        dest=a+4+2*sx(w&4095,12)
        code=simple(a+2)+f'goto L{dest:x};'
        delay_slots.add(a+2);terminal=True
    elif w==0xB:
        code=simple(a+2)+'return 0;'
        delay_slots.add(a+2);terminal=True
    elif w==0x0023:
        code=f'target=0x{a+4:08x}u+r[0];'+simple(a+2)+'switch(target){'
        code+=''.join(f'case 0x{t:08x}u:goto L{t:x};' for t in sorted(set(targets)))
        code+='default:return -2;}'
        delay_slots.add(a+2);terminal=True
    elif w>>12==0xB or w & 0xF0FF==0x400B:
        dest=a+4+2*sx(w&4095,12) if w>>12==0xB else None
        code=f'target=0x{dest:08x}u;' if dest is not None else f'target=r[{w>>8&15}];'
        code+=f'*pr=0x{a+4:08x}u;'+simple(a+2)
        code+='status=call(ctx,target,m,f,sr,r,pr);if(status)return status;'
        code+='if(f->fpscr&0x80000u)return -1;'
        delay_slots.add(a+2)
    else:
        code=simple(a)
    if not terminal:
        next_address=a+4 if a+2 in delay_slots else a+2
        assert next_address in rows
        code+=f'goto L{next_address:x};'
    out.append(f'L{a:x}: {code} /* {text} */')

source=P/f'source/{NAME}.c'
source.write_text(header+'\n'.join(out)+'\n}\n')
manifest={
    'address':hex(START),'end_exclusive':hex(END),'instruction_rows':len(rows),
    'instruction_bytes':len(rows)*2,'external_call_sites':len(calls),
    'table_entries':50,'table_unique_targets':45,
    'table_targets':[hex(t) for t in targets],
    'reachable_addresses':[hex(a) for a in sorted(seen)],
    'conditional_and_switch_edges':[[hex(a),hex(b)] for a,b in branch_edges],
    'external_call_site_addresses':[hex(a) for a in sorted(calls)],
    'delay_slot_addresses':[hex(a) for a in sorted(delay_slots)],
    'sha256':{str(path):hashlib.sha256(path.read_bytes()).hexdigest()
              for path in (BINARY,LISTING,TRANSLATOR,Path(__file__),source)},
    'scope':'Byte-checked static native C and raw-opcode reachability including 50 signed switch offsets; PR=0, both FR banks and SZ widths. Behavioral proof is separate. External callees remain services.'
}
(P/'analysis/main_dispatch_transition_translation.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(f'{len(rows)} original instructions translated; 50 entries / 45 targets; 34 external call sites')

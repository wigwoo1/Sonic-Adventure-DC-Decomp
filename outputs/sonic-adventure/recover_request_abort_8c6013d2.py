"""Emit static annotated C control flow from the saved retail instruction listing."""
import hashlib
import argparse
import re
from pathlib import Path

PROJECT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--routine', choices=('abort','finalizer','status'), default='abort')
routine = parser.parse_args().routine
specs = {'abort': (0x8C6013D2,0x8C601500,'sa_request_abort_8c6013d2',{0x8C601410}),
         'finalizer': (0x8C600CF0,0x8C600D82,'sa_request_finalize_8c600cf0',set()),
         'status': (0x8C6013A4,0x8C6013BC,'sa_request_status_8c6013a4',set())}
START, END, SYMBOL, padding = specs[routine]
binary = (PROJECT.parents[1] / 'work/sonic-adventure/extracted/1ST_READ.BIN').read_bytes()
rows = {}
for line in (PROJECT / f'analysis/instructions/{START:08x}.tsv').read_text().splitlines()[1:]:
    address, word, text, *_ = line.split('\t')
    address = int(address, 16)
    rows[address] = int(word, 16), text.lstrip('_')
assert set(range(START, END, 2)) - set(rows) == padding
for address, (word, _) in rows.items():
    assert int.from_bytes(binary[address-0x8C010000:address-0x8C010000+2], 'little') == word

def signed(value, bits):
    return value - (1 << bits) if value & (1 << (bits-1)) else value

def simple(address):
    w, _ = rows[address]
    n, m = (w >> 8) & 15, (w >> 4) & 15
    if w == 9: return ''
    if w >> 12 == 14: return f'r[{n}]=0x{signed(w&255,8)&0xFFFFFFFF:08x}u;'
    if w >> 12 == 13: return f'r[{n}]=rd(ram,0x{((address+4)&~3)+(w&255)*4:08x}u,4);'
    if w >> 12 == 9: return f'r[{n}]=sx16(rd(ram,0x{address+4+(w&255)*2:08x}u,2));'
    if w >> 12 == 7: return f'r[{n}]+=0x{signed(w&255,8)&0xFFFFFFFF:08x}u;'
    if w >> 12 == 5: return f'r[{n}]=rd(ram,r[{m}]+{(w&15)*4}u,4);'
    if w & 0xF00F == 0x6003: return f'r[{n}]=r[{m}];'
    if w & 0xF00F == 0x6002: return f'r[{n}]=rd(ram,r[{m}],4);'
    if w & 0xF00F == 0x6001: return f'r[{n}]=sx16(rd(ram,r[{m}],2));'
    if w & 0xF00F == 0x2002: return f'wr(ram,r[{n}],r[{m}],4);'
    if w & 0xF00F == 0x300C: return f'r[{n}]+=r[{m}];'
    if w & 0xF00F == 0x2006: return f'r[{n}]-=4u;wr(ram,r[{n}],r[{m}],4);'
    if w & 0xF00F == 0x6006:
        assert n != m
        return f'r[{n}]=rd(ram,r[{m}],4);r[{m}]+=4u;'
    if w & 0xF0FF == 0x4022: return f'r[{n}]-=4u;wr(ram,r[{n}],state->pr,4);'
    if w & 0xF0FF == 0x4026: return f'state->pr=rd(ram,r[{n}],4);r[{n}]+=4u;'
    if w & 0xF00F == 0x000D: return f'r[{n}]=sx16(rd(ram,r[0]+r[{m}],2));'
    if w & 0xF00F == 0x000E: return f'r[{n}]=rd(ram,r[0]+r[{m}],4);'
    if w & 0xF00F == 0x0005: return f'wr(ram,r[0]+r[{n}],r[{m}],2);'
    if w & 0xF00F == 0x2008: return f'state->sr=(state->sr&~1u)|((r[{n}]&r[{m}])==0);'
    if w & 0xFF00 == 0x8800: return f'state->sr=(state->sr&~1u)|(r[0]==0x{signed(w&255,8)&0xFFFFFFFF:08x}u);'
    if w & 0xF00F == 0x3000: return f'state->sr=(state->sr&~1u)|(r[{n}]==r[{m}]);'
    if w & 0xF00F == 0x3006: return f'state->sr=(state->sr&~1u)|(r[{n}]>r[{m}]);'
    if w & 0xF00F == 0x3002: return f'state->sr=(state->sr&~1u)|(r[{n}]>=r[{m}]);'
    if w & 0xF0FF == 0x0002: return f'r[{n}]=state->sr;'
    if w & 0xF0FF == 0x400E: return f'state->sr=r[{n}];'
    if w & 0xF0FF == 0x4009: return f'r[{n}]>>=2;'
    if w & 0xF0FF == 0x4008: return f'r[{n}]<<=2;'
    if w & 0xF00F == 0x2009: return f'r[{n}]&=r[{m}];'
    if w & 0xF00F == 0x200B: return f'r[{n}]|=r[{m}];'
    if w & 0xFF00 == 0xC900: return f'r[0]&={w&255}u;'
    if w & 0xFF00 == 0xCB00: return f'r[0]|={w&255}u;'
    raise ValueError(f'Unsupported ordinary opcode {address:08x}: {w:04x}')

header = '''/* Generated by recover_request_abort_8c6013d2.py; static native C, not an opcode interpreter.
 * Full instruction annotation is retained because decompiler output omits SR effects. */
#include <stdint.h>
#ifdef _WIN32
#define SA_EXPORT __declspec(dllexport)
#else
#define SA_EXPORT
#endif
struct sa_cpu_state { uint32_t r[16], sr, pr, pc; };
typedef int (*sa_abort_dispatch)(uint8_t *, struct sa_cpu_state *, uint32_t, void *);
static uint32_t rd(const uint8_t *ram,uint32_t address,unsigned size) {
    uint32_t at=(address&0x1fffffffu)-0x0c000000u,value=0;
    for(unsigned i=0;i<size;++i)value|=(uint32_t)ram[at+i]<<(i*8);
    return value;
}
static void wr(uint8_t *ram,uint32_t address,uint32_t value,unsigned size) {
    uint32_t at=(address&0x1fffffffu)-0x0c000000u;
    for(unsigned i=0;i<size;++i)ram[at+i]=(uint8_t)(value>>(i*8));
}
static uint32_t sx16(uint32_t value) { return (uint32_t)(int32_t)(int16_t)value; }
/* Host -2 = missing dispatcher (no mutation); -3 = execution budget reached
 * (partial state). Retail results are in R0. External services return host status. */
SA_EXPORT int sa_request_abort_8c6013d2(uint8_t *ram,struct sa_cpu_state *state,
    sa_abort_dispatch dispatch,void *context,uint32_t budget) {
    if(!dispatch)return -2;
    uint32_t *r=state->r;
    int status;
    uint32_t target,taken;
    goto L8c6013d2;
'''
if routine != 'abort':
    header = header.replace('sa_request_abort_8c6013d2(', SYMBOL+'(')
    header = header.replace('goto L8c6013d2;', f'goto L{START:08x};')
    if not any(word >> 12 == 11 or word & 0xF0FF == 0x400B for word, _ in rows.values()):
        header = header.replace('    int status;\n', '')
        header = header.replace('    uint32_t *r=state->r;', '    (void)context;\n    uint32_t *r=state->r;')
out = [header]
delays = set()
for address, (word, _) in rows.items():
    if word >> 12 in (10,11) or word & 0xFF00 in (0x8D00,0x8F00) or word & 0xF0FF == 0x400B or word == 11:
        delays.add(address+2)
targets = set()
for address, (word, _) in rows.items():
    if word >> 12 == 10: targets.add(address+4+signed(word&4095,12)*2)
    if word & 0xFF00 in (0x8900,0x8B00,0x8D00,0x8F00): targets.add(address+4+signed(word&255,8)*2)
assert not targets & delays
for address, (word, text) in rows.items():
    if address in delays: continue
    out.append(f'L{address:08x}: /* {text} */\n    if(!budget--){{state->pc=0x{address:08x}u;return -3;}}\n')
    if word == 11:
        out.append(f'    target=state->pr;{simple(address+2)}state->pc=target;return 0;\n')
    elif word >> 12 == 10:
        target = address+4+signed(word&4095,12)*2
        out.append(f'    {simple(address+2)}goto L{target:08x};\n')
    elif word & 0xFF00 in (0x8900,0x8B00,0x8D00,0x8F00):
        target = address+4+signed(word&255,8)*2
        bt = word & 0xFF00 in (0x8900,0x8D00)
        delayed = word & 0xFF00 in (0x8D00,0x8F00)
        out.append(f'    taken={"!!" if bt else "!"}(state->sr&1u);{simple(address+2) if delayed else ""}'
                   f'if(taken)goto L{target:08x};goto L{address+(4 if delayed else 2):08x};\n')
    elif word >> 12 == 11 or word & 0xF0FF == 0x400B:
        expr = f'0x{address+4+signed(word&4095,12)*2:08x}u' if word >> 12 == 11 else f'r[{(word>>8)&15}]'
        out.append(f'    target={expr};state->pr=0x{address+4:08x}u;{simple(address+2)}state->pc=target;'
                   f'status=dispatch(ram,state,target,context);if(status)return status;goto L{address+4:08x};\n')
    else:
        out.append(f'    {simple(address)}goto L{address+2:08x};\n')
out.append('}\n')
source = PROJECT / f'source/{SYMBOL}.c'
output = ''.join(out)
if routine != 'abort' and output.count('wr(') == 1:
    output = re.sub(r'static void wr\([^}]+}\n', '', output)
source.write_text(output, encoding='utf-8')
print(f'Generated {len(rows)} annotated retail instructions; source SHA256 {hashlib.sha256(source.read_bytes()).hexdigest()}')
